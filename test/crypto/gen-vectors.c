/*
 * gen-vectors.c - offline generator for the crypto conformance test vectors.
 *
 * Generates the PEM key files in vectors/ and vectors.h with the expected
 * key identities, digests and signatures. Run once, commit the result.
 * Requires an OpenSSL (libcrypto) development environment.
 *
 *	build: cc -o gen-vectors gen-vectors.c -lcrypto
 *	run:   ./gen-vectors vectors/
 *
 * SPDX-License-Identifier: GPL-2.0-only
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <openssl/pem.h>
#include <openssl/evp.h>
#include <openssl/rsa.h>
#include <openssl/ec.h>
#include <openssl/obj_mac.h>

static const char *msg = "apk-tools crypto conformance test vector message";

static void die(const char *what)
{
	fprintf(stderr, "FAILED: %s\n", what);
	exit(1);
}

static void write_pem_file(const char *dir, const char *name,
			   int priv, const EVP_PKEY *pkey, int traditional)
{
	char path[512];
	snprintf(path, sizeof path, "%s/%s", dir, name);
	FILE *f = fopen(path, "w");
	if (!f) die(path);
	BIO *b = BIO_new_fp(f, BIO_CLOSE);
	int r;
	if (priv && traditional) {
		if (EVP_PKEY_is_a(pkey, "RSA"))
			r = PEM_write_bio_RSAPrivateKey(b, EVP_PKEY_get0_RSA((EVP_PKEY*)pkey), NULL, NULL, 0, NULL, NULL);
		else
			r = PEM_write_bio_ECPrivateKey(b, EVP_PKEY_get0_EC_KEY((EVP_PKEY*)pkey), NULL, NULL, 0, NULL, NULL);
	} else if (priv) {
		r = PEM_write_bio_PrivateKey(b, pkey, NULL, NULL, 0, NULL, NULL);
	} else {
		r = PEM_write_bio_PUBKEY(b, pkey);
	}
	if (r != 1) die(path);
	BIO_free(b);
}

/* identity as defined by apk: sha512(i2d_PublicKey(key)) truncated to 16 bytes */
static void key_id(const EVP_PKEY *pkey, unsigned char *id)
{
	unsigned char *pub = NULL;
	int len = i2d_PublicKey((EVP_PKEY *)pkey, &pub);
	if (len < 0) die("i2d_PublicKey");
	unsigned char dig[EVP_MAX_MD_SIZE];
	unsigned int dlen = sizeof dig;
	if (EVP_Digest(pub, len, dig, &dlen, EVP_sha512(), NULL) != 1) die("sha512");
	memcpy(id, dig, 16);
	OPENSSL_free(pub);
}

static void digest_of(const void *ptr, size_t sz, const EVP_MD *md,
		      unsigned char *out, unsigned int *outlen)
{
	if (EVP_Digest(ptr, sz, out, outlen, md, NULL) != 1) die("EVP_Digest");
}

static void rsa_sign(const EVP_PKEY *pkey, const EVP_MD *md,
		     unsigned char *sig, size_t *siglen)
{
	EVP_MD_CTX *ctx = EVP_MD_CTX_new();
	if (EVP_DigestSignInit(ctx, NULL, md, NULL, pkey) != 1) die("DigestSignInit");
	*siglen = 256;
	if (EVP_DigestSign(ctx, sig, siglen, msg, strlen(msg)) != 1) die("DigestSign");
	EVP_MD_CTX_free(ctx);
}

static void ecdsa_sign(const EVP_PKEY *pkey, const EVP_MD *md,
		       unsigned char *sig, size_t *siglen)
{
	EVP_MD_CTX *ctx = EVP_MD_CTX_new();
	if (EVP_DigestSignInit(ctx, NULL, md, NULL, pkey) != 1) die("DigestSignInit");
	*siglen = 139;
	if (EVP_DigestSign(ctx, sig, siglen, msg, strlen(msg)) != 1) die("DigestSign");
	EVP_MD_CTX_free(ctx);
}

static void print_hex(FILE *f, const unsigned char *d, size_t n, int per_line)
{
	for (size_t i = 0; i < n; i++) {
		if (i % per_line == 0) fprintf(f, "\n\t\t");
		fprintf(f, "0x%02x,", d[i]);
	}
	fprintf(f, "\n};\n");
}

int main(int argc, char **argv)
{
	const char *dir = argc > 1 ? argv[1] : ".";
	unsigned char id[16], dig[EVP_MAX_MD_SIZE], sig[256];
	unsigned int dlen;
	size_t siglen;

	EVP_PKEY *rsa = EVP_RSA_gen(2048);
	if (!rsa) die("EVP_RSA_gen");
	EVP_PKEY *ec = EVP_EC_gen("prime256v1");
	if (!ec) die("EVP_EC_gen");

	write_pem_file(dir, "rsa-priv.pem", 1, rsa, 1);
	write_pem_file(dir, "rsa-priv-p8.pem", 1, rsa, 0);
	write_pem_file(dir, "rsa-pub.pem", 0, rsa, 0);
	write_pem_file(dir, "ec-priv.pem", 1, ec, 1);
	write_pem_file(dir, "ec-priv-p8.pem", 1, ec, 0);
	write_pem_file(dir, "ec-pub.pem", 0, ec, 0);

	char path[512];
	snprintf(path, sizeof path, "%s/vectors.h", dir);
	FILE *f = fopen(path, "w");
	if (!f) die(path);
	fprintf(f, "/* generated by test/crypto/gen-vectors.c - do not edit */\n\n");

	key_id(rsa, id);
	fprintf(f, "static const uint8_t id_rsa[16] = {");
	print_hex(f, id, 16, 16);
	key_id(ec, id);
	fprintf(f, "static const uint8_t id_ec[16] = {");
	print_hex(f, id, 16, 16);

	fprintf(f, "\nstatic const char *test_msg = \"%s\";\n", msg);

	digest_of(msg, strlen(msg), EVP_sha1(), dig, &dlen);
	fprintf(f, "static const uint8_t dig_sha1[20] = {");
	print_hex(f, dig, 20, 20);
	digest_of(msg, strlen(msg), EVP_sha256(), dig, &dlen);
	fprintf(f, "static const uint8_t dig_sha256[32] = {");
	print_hex(f, dig, 32, 16);
	digest_of(msg, strlen(msg), EVP_sha512(), dig, &dlen);
	fprintf(f, "static const uint8_t dig_sha512[64] = {");
	print_hex(f, dig, 64, 16);

	rsa_sign(rsa, EVP_sha256(), sig, &siglen);
	fprintf(f, "static const uint8_t sig_rsa_sha256[256] = {");
	print_hex(f, sig, 256, 16);
	rsa_sign(rsa, EVP_sha512(), sig, &siglen);
	fprintf(f, "static const uint8_t sig_rsa_sha512[256] = {");
	print_hex(f, sig, 256, 16);

	ecdsa_sign(ec, EVP_sha256(), sig, &siglen);
	fprintf(f, "static const uint8_t sig_ec_sha256[%zu] = {", siglen);
	print_hex(f, sig, siglen, 16);
	fprintf(f, "#define SIG_EC_SHA256_LEN %zu\n", siglen);

	fclose(f);
	printf("vectors written to %s\n", dir);
	return 0;
}
